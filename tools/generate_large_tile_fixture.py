#!/usr/bin/env python3
"""Regenerate public synthetic NSP2/44 codec fixtures; no game assets."""
import lzma
from pathlib import Path
import struct

from tile_filter import filter_tiles


def main():
    records = bytearray(4 * 770)
    for ty in range(2):
        for tx in range(2):
            tile = ty * 2 + tx
            records[tile * 770:tile * 770 + 2] = bytes((1 if tx else 16, 1 if ty else 16))
    for y in range(17):
        for x in range(17):
            tile, pixel = y // 16 * 2 + x // 16, y % 16 * 16 + x % 16
            struct.pack_into('<H', records, tile * 770 + 2 + pixel * 2, (x * 991 + y * 771) & 65535)
            records[tile * 770 + 514 + pixel] = (x + y * 13) % 256
    raw = bytes(records) * 340
    fixtures = [(f'large_tiles_mode{mode}', filter_tiles(raw, mode) if mode else raw) for mode in range(3)]
    fixtures.append(('large_lzma2_zeros', bytes(1024 * 1024)))
    lines = ['// Generated by tools/generate_large_tile_fixture.py from synthetic pixels.']
    for name, data in fixtures:
        filters = [dict(id=lzma.FILTER_LZMA2, preset=9, dict_size=1024 * 1024)]
        encoded = lzma.compress(data, format=lzma.FORMAT_RAW, filters=filters)
        assert lzma.decompress(encoded, format=lzma.FORMAT_RAW, filters=filters) == data
        lines.append(f'static const uint8_t {name}[]={{')
        lines.extend('    ' + ','.join(f'0x{v:02x}' for v in encoded[i:i + 16]) + ',' for i in range(0, len(encoded), 16))
        lines.append('};')
    path = Path(__file__).resolve().parents[1] / 'tests/fixtures/large_tile_blocks.inc'
    path.write_text('\n'.join(lines) + '\n')
    print(f'Generated {path.name}: {path.stat().st_size} source bytes')


if __name__ == '__main__':
    main()
