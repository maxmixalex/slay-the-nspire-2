#!/usr/bin/env python3
"""Generate the compact .NET 9 invariant-uppercase seed table.

Input: Unicode 15.1 UnicodeData.txt (not bundled; the generated data is covered
by third_party/unicode/LICENSE). The pinned .NET 9.0.7 ChangeCaseInvariant uses
the Unicode simple uppercase mapping, except U+0131 remains unchanged.
No normalization, full-case expansion, language-specific rule or runtime
Unicode dependency is introduced.
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UNICODE_SHA256 = '2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86'


def generate(source: Path) -> str:
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != UNICODE_SHA256:
        raise ValueError('Expected the unmodified Unicode 15.1 UnicodeData.txt')
    pairs = []
    for line in raw.decode('utf-8').splitlines():
        fields = line.split(';')
        cp = int(fields[0], 16)
        if fields[12] and cp >= 128 and cp != 0x0131:
            upper = int(fields[12], 16)
            if cp != upper:
                pairs.append((cp, upper))
    ranges, single = [], []
    i = 0
    while i < len(pairs):
        cp, upper = pairs[i]
        delta = upper - cp
        step = pairs[i + 1][0] - cp if i + 1 < len(pairs) else 0
        j = i + 1
        if step in (1, 2):
            while (j < len(pairs) and pairs[j][0] == cp + (j - i) * step
                   and pairs[j][1] - pairs[j][0] == delta):
                j += 1
        if j - i >= 2:
            ranges.append((cp, pairs[j - 1][0] | (0x80000000 if step == 2 else 0), delta))
            i = j
        else:
            assert cp <= 0xffff and upper <= 0xffff
            single.append((cp, upper))
            i += 1
    out = [
        '// Generated by tools/generate_seed_case_tables.py; do not edit.',
        '// Unicode 15.1 data: third_party/unicode/LICENSE.',
        '// .NET 9.0.7 invariant casing leaves U+0131 unchanged.',
        '// ASCII is handled directly. The top end bit marks a stride of two.',
        'struct SeedCaseRange { uint32_t first, end; int32_t delta; };',
        'struct SeedCasePair { uint16_t lower, upper; };',
        'static constexpr SeedCaseRange SeedCaseRanges[] = {',
    ]
    out += [f'    {{0x{lo:x}, 0x{hi:08x}, {delta}}},' for lo, hi, delta in ranges]
    out += ['};', 'static constexpr SeedCasePair SeedCasePairs[] = {']
    out += [f'    {{0x{lo:04x}, 0x{hi:04x}}},' for lo, hi in single]
    out += ['};', 'static_assert(sizeof SeedCaseRanges + sizeof SeedCasePairs == 1488,',
            '              "Seed casing data must retain its bounded read-only footprint");', '']
    return '\n'.join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('unicode_data', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT / 'src/seed_case_tables.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(args.unicode_data)
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit('Seed case table differs from the pinned Unicode source')
    else:
        args.output.write_text(result)
    print('Seed casing: 1,423 non-ASCII mappings; 87 ranges + 111 pairs; 1,488 bytes')


if __name__ == '__main__':
    main()
