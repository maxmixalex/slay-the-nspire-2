#!/usr/bin/env python3
"""Rasterize only the built-in boot labels from an open Noto Sans CJK font.

The output is a small 14px monochrome subset, not an installable font. Supply
NotoSansCJK-Regular.ttc from fonts-noto-cjk; SC is collection index 2. The OFL
notice in licenses/Noto-Boot-OFL.txt must accompany binary redistributions.
"""
import argparse
import hashlib
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]

def build(font_path, output):
    source = (ROOT / "include/locale_boot.hpp").read_text(encoding="utf-8")
    chars = sorted(set(re.findall(r"[\u3400-\u9fff]", source)))
    font = ImageFont.truetype(str(font_path), 14, index=2)
    assert font.getname()[0] == "Noto Sans CJK SC", font.getname()
    rows = []
    for char in chars:
        image = Image.new("L", (14, 14))
        ImageDraw.Draw(image).text((0, 0), char, font=font, fill=255, anchor="lt")
        masks = [sum((image.getpixel((x, y)) >= 96) << x for x in range(14)) for y in range(14)]
        if not any(masks):
            raise ValueError(f"Blank boot glyph: {char}")
        rows.append("    {0x%04x,{%s}}, // %s" % (ord(char), ",".join("0x%04x" % m for m in masks), char))
    digest = hashlib.sha256(font_path.read_bytes()).hexdigest()
    text = """#pragma once
// Generated by tools/build_boot_glyphs.py; do not hand edit the bitmap subset.
// Noto Sans CJK SC, Copyright 2014-2021 Adobe; SIL OFL 1.1.
// Full notice: licenses/Noto-Boot-OFL.txt. No game font or resource is used.
// Source NotoSansCJK-Regular.ttc SHA-256: %s
#include <stdint.h>
namespace spire {
struct BootGlyph {uint16_t codepoint,rows[14];};
inline constexpr BootGlyph BootGlyphs[]={
%s
};
} // namespace spire
""" % (digest, "\n".join(rows))
    output.write_text(text, encoding="utf-8")
    print(f"{len(chars)} boot glyphs, {len(chars) * 30} bitmap/index bytes")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "include/locale_boot_glyphs.hpp")
    args = parser.parse_args()
    build(args.font, args.output)
