#!/usr/bin/env python3
"""Emit only resource-key associations from the pinned PowerModel getters."""
import argparse
from pathlib import Path
from generate_keyword_hovers import ROOT, REFERENCE, extras, property_text, slug


def associations(name, source):
    if name in ('TemporaryStrengthPower', 'TemporaryDexterityPower', 'TemporaryFocusPower'):
        base = name.removeprefix('Temporary')
        return [('Special', 'POWER_ORIGIN', 0), ('Power', slug(base), 0)]
    if name == 'SwipePower':
        return [('Special', 'POWER_CAPTURED_CARD', 0)]
    if name == 'WitheringPresencePower':
        return [('Special', 'POWER_WITHER', 0)]
    if name in ('ChainsOfBindingPower', 'HexPower', 'VitalSparkPower'):
        kind = {'ChainsOfBindingPower': 'BOUND', 'HexPower': 'HEXED', 'VitalSparkPower': 'TAINTED'}[name]
        return [('Affliction', kind, 0 if kind == 'BOUND' else 4)]
    return extras(name, source)


def generate(reference):
    rows, flattened = [], []
    for path in sorted((reference/'MegaCrit.Sts2.Core.Models.Powers').glob('*.cs')):
        source = path.read_text()
        if not property_text(source, 'ExtraHoverTips'):
            continue
        values = associations(path.stem, source)
        rows.append(f' {{"{slug(path.stem)}",{len(flattened)},{len(values)}}},')
        flattened.extend(values)
    if len(rows) != 99:
        raise ValueError('Pinned power association getter count changed')
    return '\n'.join([f'// {REFERENCE}; resource keys only, no source text or assets.',
        '// Generated by tools/generate_power_hovers.py; dynamic sources stay explicit.',
        'static const HoverTipSpec power_hover_specs[]={',
        *[f' {{HoverTipKind::{kind},"{key}",{flags}}},' for kind, key, flags in flattened],
        '};', 'struct PowerHoverCatalog {const char*key;uint16_t first;uint8_t count;};',
        'static const PowerHoverCatalog power_hover_catalog[]={', *rows, '};', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('reference', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(args.reference)
    path = ROOT/'src/power_hover_catalog.inc'
    if args.check:
        if path.read_text() != result:
            raise SystemExit('Power association catalog differs from the pinned source')
    else:
        path.write_text(result)


if __name__ == '__main__':
    main()
