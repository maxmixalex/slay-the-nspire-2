"""Complete fresh original-game artwork and publish matching calculator data.

Inputs are the editions generated by this recipe. Historical private packs,
recovery spools and manually prepared receipts are never required. Optional
orphan-index instruction profiling is used only when a matching ELF is present.
"""
from __future__ import annotations

import json
from pathlib import Path
import time

ROOT = Path(__file__).resolve().parents[1]
# Accepted UI23 artwork policy. Reduced editions keep their original colors.
DEFAULT_QUALITY_POLICY = 'bounded-a5'
DEFAULT_PRESERVE_SELECTION = False
DEFAULT_SELECTION_POLICY = 'dark-safe-a6'
DEFAULT_SELECTION_OVERRIDES = {0: '555a8', 2: '555a8', 3: '555a8'}


def save_result(path, data, receipt):
    import content_tiles as t
    path = Path(path)
    receipt.update(complete=True, output_bytes=len(data), output_sha256=t.sha256(data))
    t.atomic_bytes(path, data)
    t.atomic_bytes(path.with_suffix('.json'), (json.dumps(receipt, indent=2)+'\n').encode())
    print(json.dumps({key: value for key, value in receipt.items()
                      if key in ('complete', 'output_bytes', 'output_sha256', 'stage')}), flush=True)


def retile_fresh(input_path, output_path, work, workers):
    """Dice newly sampled sparse actor pieces without a restoration archive."""
    import coalesce_tile_resources as coalesce
    import content_tiles as t
    import retile_character_ui12 as dice
    import retile_appended_resources as retile
    data = Path(input_path).read_bytes(); source = coalesce.view(data)
    t.require(source.version == 44 and len(source.aux) == 7206,
              'Fresh actor dicing requires the complete original-derived UI22 actor catalog')
    work = Path(work); work.mkdir(parents=True, exist_ok=True)
    # Registered overflow pieces are auxiliary roots, not ordinary clip
    # samples. Inspect every retained sparse image so those pieces are included.
    selected = set()
    for image, descriptor in enumerate(source.images):
        if descriptor[3] != 6 and source.image_raw(image)[2] == 4:
            selected.add(image)
    if selected:
        plan = dice.make_plan(source, work, selected, precision=8)
        plan['compact_replaced_directory'] = True
        encoded = retile.compress_plan(plan, work, work/'encoded', workers)
        output, details = retile.rewrite(source, plan, encoded)
        proof = dice.verify(source, output, plan, work)
    else:
        output, details, proof = data, {}, {'exact_sparse_images': 0}
    save_result(output_path, output, dict(stage='fresh_actor_dicing', input_sha256=t.sha256(data),
        selected_sparse_images=len(selected), precision='RGB565/alpha8 exact',
        historical_recovery_inputs=False, details=details, verification=proof))


def codec45(input_path, output_path, work, workers):
    import coalesce_tile_resources as coalesce
    import content_tiles as t
    import struct
    data = Path(input_path).read_bytes(); source = coalesce.view(data)
    t.require(source.version == 44, 'Selection preparation requires the preceding fresh NSP2/44 pack')
    # NSP45 remains compatible with the existing dense TGR1/TGR2 streams.
    # Keep them intact: optional color conversion must not receive TGR3 data,
    # and changing a codec is unnecessary for the selection representation.
    output = bytearray(data); struct.pack_into('<I', output, 4, 45); output = bytes(output)
    target = coalesce.view(output)
    t.require(output[:4] == data[:4] and output[8:] == data[8:] and
              target.images == source.images and target.clips == source.clips and
              target.aux == source.aux, 'Wire version preparation changed resource payloads')
    save_result(output_path, output, dict(stage='selection_codec45', input_sha256=t.sha256(data),
        existing_pixel_codecs_unchanged=True, all_payload_bytes_unchanged=True))


def optional_prune(input_path, output_path, elf_path):
    import content_tiles as t
    data = Path(input_path).read_bytes(); elf = Path(elf_path) if elf_path else None
    if elf is not None and elf.is_file():
        from prune_orphan_index_records_ui22 import convert_bytes, ArmIndices
        output, details = convert_bytes(data, ArmIndices(elf))
        details['optimization_executed'] = True
    else:
        output = data
        details = dict(optimization_executed=False,
            reason='Optional complete linked-ARM profiling requires a matching launcher ELF; all records retained',
            orphan_records_removed=0, saved_bytes=0)
    save_result(output_path, output, dict(stage='optional_orphan_pruning',
        input_sha256=t.sha256(data), **details))


def quality(input_path, output_path, work, workers, policy, preserve_selection,
            selection_policy=None, selection_overrides=None):
    import content_tiles as t
    data = Path(input_path).read_bytes()
    if policy == 'exact':
        save_result(output_path, data, dict(stage='quality', policy='exact',
            input_sha256=t.sha256(data), exact_pixels=True))
        return
    import animation_color_candidates_ui23 as colors
    import coalesce_color_candidates_ui23 as coalescer
    source = colors.view(data)
    results = colors.convert(source, policy, workers=workers, preserve_static=True,
                             preserve_selection=preserve_selection, selection_policy=selection_policy,
                             selection_overrides=selection_overrides)
    quantized = colors.rewrite(source, {}, results)
    proof = colors.verify(source, quantized, results, policy, selection_policy, selection_overrides)
    output, compaction = coalescer.convert(quantized, Path(work), workers=workers)
    save_result(output_path, output, dict(stage='quality', policy=policy,
        input_sha256=t.sha256(data), static_art_preserved=True,
        selection_art_preserved=preserve_selection, selection_policy=selection_policy,
        selection_overrides=selection_overrides or {},
        color_verification=proof,
        exact_tile_coalescing=compaction))


def sparse_exact(input_path, output_path, work, workers):
    import coalesce_tile_resources as coalesce
    import compact_sparse_tiles as sparse
    import content_tiles as t
    data = Path(input_path).read_bytes(); source = coalesce.view(data)
    plan, details = sparse.make_plan(source, Path(work), workers=workers)
    # Implicit frame geometry requires version 46 even though TGR3 began at 45.
    output, _ = coalesce.rewrite(data, plan, version=source.version)
    proof = sparse.verify(data, output, plan)
    t.require(len(output) <= len(data), 'Exact sparse conversion increased the resource')
    save_result(output_path, output, dict(stage='exact_sparse_tiles',
        input_sha256=t.sha256(data), exact_pixels=True, resident_bytes_added=0,
        details=details, verification=proof))


def retune_exact(input_path, output_path, work, workers):
    import content_tiles as t
    import retune_color_contexts_ui23 as retune
    data = Path(input_path).read_bytes()
    output, proof = retune.convert(data, Path(work), workers=workers)
    t.require(len(output) <= len(data), 'Exact literal-context retuning increased the resource')
    save_result(output_path, output, dict(stage='exact_literal_contexts',
        input_sha256=t.sha256(data), exact_pixels=True, resident_bytes_added=0,
        literal_contexts_never_larger=True, profiles=retune.PROFILES, verification=proof))


def validate_install(artwork_path, output, codes, no_animations):
    import content_tiles as t
    import coalesce_tile_resources as coalesce
    import no_animations as reduced
    import split_content as split
    import storage_parts as storage
    from release_content_guard import validate_release_content
    from converter_storage import edition_files
    output = Path(output); directory = output/'data'; started = time.monotonic()
    artwork = Path(artwork_path).read_bytes(); source = coalesce.view(artwork)
    t.require(reduced.reduced(artwork) == no_animations, 'Requested animation profile does not match the artwork')
    guard = validate_release_content(artwork, 'ui23')
    refresh = json.loads((directory/'artwork-refresh-receipt.json').read_text())
    common = storage.join_parts((directory/'nSpire2.dat.tns').read_bytes(),
        {name: (directory/name).read_bytes() for name in storage.PART_FILES})
    locales = {}
    for code in codes:
        logical = split.reconstruct(common, (directory/f'nSpire2.{code}.dat.tns').read_bytes(), code)
        view = coalesce.view(logical)
        t.require(t.sha256(logical) == refresh['locales'][code]['logical_sha256'],
                  'Published locale differs from its verified artwork refresh')
        t.require(len(view.images) == len(source.images) and
                  all(before[1:] == after[1:] for before, after in zip(source.images, view.images)),
                  'Published locale image catalog differs')
        t.require(view.cards == source.cards and view.clips == source.clips and view.aux == source.aux,
                  'Published locale has mismatched gameplay or animation identities')
        t.require(reduced.reduced(logical) == no_animations, 'Published locale lost its presentation profile')
        locales[code] = dict(logical_bytes=len(logical), logical_sha256=t.sha256(logical),
            stored_bytes=(directory/f'nSpire2.{code}.dat.tns').stat().st_size,
            glyphs=len(view.glyphs), strings=len(view.strings), roundtrip_verified=True)
    files = edition_files(directory, codes)
    unexpected = [code for code in split.LANGUAGES if code not in codes and
                  (directory/f'nSpire2.{code}.dat.tns').exists()]
    t.require(not unexpected,
              'Output contains unrequested old locale files; choose a clean output directory: '+','.join(unexpected))
    report = dict(schema=1, status='complete', complete=True, source='original-game-directory',
        content_version=source.version, animation_profile='reduced-poses' if no_animations else 'full',
        original_clip_counts_clocks_pivots_unchanged=True, languages=codes,
        installed_data_bytes=sum(path.stat().st_size for path in files),
        files={path.name: dict(bytes=path.stat().st_size, sha256=t.sha256(path.read_bytes())) for path in files},
        locales=locales, release_content=guard, elapsed_seconds=time.monotonic()-started,
        launcher_included=False, calculator_performance_measured=False)
    t.atomic_bytes(output/'converter-receipt.json', (json.dumps(report, indent=2)+'\n').encode())
    print(json.dumps({key: report[key] for key in ('status', 'content_version', 'animation_profile',
                                                  'languages', 'installed_data_bytes')}), flush=True)


def execute_builtin(module, arguments):
    if module == '@fresh-actor-dicing':
        retile_fresh(*arguments[:3], int(arguments[3]))
    elif module == '@fresh-codec45':
        codec45(*arguments[:3], int(arguments[3]))
    elif module == '@optional-orphan-prune':
        optional_prune(*arguments)
    elif module == '@final-quality':
        quality(*arguments[:3], int(arguments[3]), arguments[4], arguments[5] == 'true',
                arguments[6] or None, {int(key): value for key, value in json.loads(arguments[7]).items()})
    elif module == '@final-sparse':
        sparse_exact(*arguments[:3], int(arguments[3]))
    elif module == '@final-retune':
        retune_exact(*arguments[:3], int(arguments[3]))
    elif module == '@validate-install':
        validate_install(arguments[0], arguments[1], arguments[2].split(','), arguments[3] == 'true')
    else:
        return False
    return True


def add_final_stages(recipe, source_editions, output, codes, no_animations):
    from converter_storage import add_storage_stages, edition_files
    codes = list(codes); output = Path(output)
    logical, physical = add_storage_stages(recipe, source_editions, codes)
    workers = min(2, recipe.workers)
    for name, module, receipt in (
        ('native-framed20', 'framed_animation_ui20_assets', None),
        ('native-actors22', 'actor_animation_ui22', 'actor-animation-ui22-receipt.json'),
    ):
        target = recipe.directory(name)/'eng.nsp'; work = recipe.directory('cache')/name
        recipe.add(name, module, ['--input', logical, '--pck', recipe.pck,
            '--runtime', recipe.runtime, '--dotnet', recipe.dotnet, '--work', work, '--output', target],
            [target, work/receipt if receipt else target.with_suffix('.json')])
        logical = target
    for name, module in (('fresh-actor-dicing', '@fresh-actor-dicing'), ('codec45', '@fresh-codec45')):
        target = recipe.directory(name)/'eng.nsp'
        recipe.add(name, module, [logical, target, recipe.directory('cache')/name, workers],
                   [target, target.with_suffix('.json')])
        logical = target
    for name, module in (('selection45', 'finish_artwork_ui22'),
                         ('retirement45', 'retire_legacy_resources_ui22')):
        target = recipe.directory(name)/'eng.nsp'
        work = recipe.directory('cache')/name
        receipt = work/'retirement-receipt.json' if name == 'retirement45' else target.with_suffix('.json')
        recipe.add(name, module, ['--input', logical, '--output', target,
            '--work', work, '--workers', workers], [target, receipt])
        logical = target
    target = recipe.directory('ancient-scenes45')/'eng.nsp'
    exact_scenes = no_animations or getattr(recipe, 'quality_policy', DEFAULT_QUALITY_POLICY) == 'exact'
    scene_options = [] if exact_scenes else ['--bounded-color-hold', '--key-interval', 32, '--retained-planes']
    recipe.add('ancient-scenes45', 'ancient_scene_ui23', ['--input', logical,
        '--output', target, '--pck', recipe.pck, '--runtime', recipe.runtime,
        '--dotnet', recipe.dotnet, '--work', recipe.directory('cache/ancient-scenes45'),
        '--workers', workers, *scene_options], [target,target.with_suffix('.json')]); logical = target
    target = recipe.directory('implicit46')/'eng.nsp'
    recipe.add('implicit46', 'implicit_tile_geometry_ui22', ['--input', logical,
        '--output', target, '--work', recipe.directory('cache/implicit46'),
        '--workers', workers], [target,target.with_suffix('.json')]); logical = target
    elf = next((path for path in (ROOT/'converter_helpers/nSpire2.elf', ROOT/'build/ndless/nSpire2.elf')
                if path.is_file()), None)
    target = recipe.directory('pruned46')/'eng.nsp'
    recipe.add('pruned46', '@optional-orphan-prune', [logical, target, str(elf) if elf else ''],
               [target, target.with_suffix('.json')]); logical = target
    target = recipe.directory('quality46')/'eng.nsp'
    selection_policy = None if no_animations else getattr(recipe, 'selection_policy', DEFAULT_SELECTION_POLICY)
    selection_overrides = {} if no_animations else getattr(recipe, 'selection_overrides', DEFAULT_SELECTION_OVERRIDES)
    recipe.add('quality46', '@final-quality', [logical, target, recipe.directory('cache/quality46'), workers,
        'exact' if no_animations else getattr(recipe, 'quality_policy', DEFAULT_QUALITY_POLICY),
        'true' if no_animations or getattr(recipe, 'preserve_selection', DEFAULT_PRESERVE_SELECTION) else 'false',
        selection_policy or '', json.dumps(selection_overrides, sort_keys=True)],
        [target, target.with_suffix('.json')]); logical = target
    if not no_animations:
        for name, module in (('sparse46', '@final-sparse'), ('retuned46', '@final-retune')):
            target = recipe.directory(name)/'eng.nsp'
            recipe.add(name, module, [logical, target, recipe.directory('cache')/name, workers],
                       [target, target.with_suffix('.json')])
            logical = target
    if no_animations:
        target = recipe.directory('reduced46')/'eng.nsp'; work = recipe.directory('cache/reduced46')
        recipe.add('reduced46', 'no_animations', ['--input', logical, '--output', target,
            '--work', work, '--workers', workers], [target, work/'no-animations-receipt.json'])
        logical = target
    recipe.add('publish-locales', 'refresh_artwork_resources', ['--artwork', logical,
        '--input', physical, '--output', output/'data', '--work', recipe.directory('verified-locales'),
        '--locales', *codes], edition_files(output/'data', codes)+[output/'data/artwork-refresh-receipt.json'])
    recipe.add('validate-install', '@validate-install', [logical, output, ','.join(codes),
        'true' if no_animations else 'false'], [output/'converter-receipt.json'])
