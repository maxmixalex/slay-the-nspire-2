#!/usr/bin/env python3
"""Append the pinned three-profile screen's private artwork and localized text.

The public catalog contains source paths and keys only. Existing image/clip/model
indices and payloads survive unchanged. Fonts are replaced after this step by
replace_original_glyphs.py, so these labels receive the same real font faces.
"""
from __future__ import annotations

import argparse
from collections import OrderedDict
import json
from pathlib import Path

from PIL import Image

import content_tiles as tiles
from patch_feedback_assets import SOURCE_PCK_SHA256, write_image
from patch_frontend_assets import patch_pack
from patch_ui7_assets import authored_tint
from pck import Pack
from world_scene_assets import load_scene_texture

VERSION, BASE_AUX, AUXILIARY, CLIPS, STRINGS = 26, 1881, 1889, 1753, 8704
TEXT_KEYS = (
    'OPEN_PROFILE_SCREEN.description', 'OPEN_PROFILE_SCREEN.title',
    'PROFILE_SCREEN.BUTTON.chooseProfileMessage', 'PROFILE_SCREEN.BUTTON.dateFormat',
    'PROFILE_SCREEN.BUTTON.description', 'PROFILE_SCREEN.BUTTON.empty',
    'PROFILE_SCREEN.BUTTON.title', 'PROFILE_SCREEN.DELETE_BUTTON.label',
    'PROFILE_SCREEN.DELETE_CONFIRM_POPUP.cancel', 'PROFILE_SCREEN.DELETE_CONFIRM_POPUP.delete',
    'PROFILE_SCREEN.DELETE_CONFIRM_POPUP.description', 'PROFILE_SCREEN.DELETE_CONFIRM_POPUP.title',
)
TEXTS = tuple((8400+i, 'main_menu_ui.'+key) for i, key in enumerate(TEXT_KEYS))
SPECS = (
    ('icon-1', 'images/ui/profile/profile_icon_1.png', (9, 9), 1),
    ('icon-2', 'images/ui/profile/profile_icon_2.png', (9, 9), 1),
    ('icon-3', 'images/ui/profile/profile_icon_3.png', (9, 9), 1),
    ('panel', 'images/ui/reward_screen/reward_panel.png', (84, 107), 1),
    ('panel-focus', 'images/ui/reward_screen/reward_panel.png', (84, 107), 1.3),
    ('current-marker', 'images/packed/map/icons/map_marker_ironclad.png', (9, 12), 1),
    ('delete', 'images/packed/main_menu/delete_button.png', (15, 15), 1),
    ('delete-focus', 'images/packed/main_menu/delete_button.png', (15, 15), 1.4),
)


def generated_index():
    return '// Original profile localization keys; generated by patch_profile_assets.py.\n'+''.join(
        ' {"'+key+'",'+str(slot)+'},\n' for slot, key in sorted(TEXTS, key=lambda row: row[1]))


def build_art(path, cache):
    cache.mkdir(parents=True, exist_ok=True)
    pack, textures = Pack(path), OrderedDict()
    try:
        scene = pack.read('scenes/screens/profiles/profile_screen.tscn').decode()
        for expected in ('offset_left = -664.0', 'offset_top = -280.0',
                         'theme_override_constants/separation = 24', 'offset_top = -252.0'):
            tiles.require(expected in scene, 'Pinned profile layout changed: '+expected)
        button = pack.read('scenes/screens/profiles/profile_button.tscn').decode()
        tiles.require('custom_minimum_size = Vector2(440, 560)' in button,
                      'Pinned profile button minimum changed')
        images = []
        for key, source, size, brightness in SPECS:
            original = load_scene_texture(pack, source, cache=textures).convert('RGBA')
            picture = authored_tint(original, (1, 1, brightness)) if brightness != 1 else original
            picture = picture.resize(size, Image.Resampling.LANCZOS)
            row = write_image(cache, 'profile-'+key, picture)
            row.update(key=key, source=source, source_size=list(original.size),
                       auxiliary=BASE_AUX+len(images))
            picture.save(cache/('profile-'+key+'.png'))
            images.append(row)
        localized = {}
        for language in ('eng', 'zhs'):
            table = json.loads(pack.read('localization/'+language+'/main_menu_ui.json'))
            localized[language] = {}
            for _, key in TEXTS:
                text = table.get(key.split('.', 1)[1])
                tiles.require(isinstance(text, str) and text and '\0' not in text,
                              'Missing pinned profile text: '+language+'/'+key)
                localized[language][key] = text
    finally:
        pack.close()
    manifest = dict(schema=1, reference='v0.111.0 / 41cef1ea', source_pck_sha256=SOURCE_PCK_SHA256,
                    output_version=VERSION, images=images, clips=[], localized_text=localized,
                    auxiliary_count=AUXILIARY, runtime_added_pixel_buffers=0)
    tiles.atomic_bytes(cache/'profile-assets.json', json.dumps(manifest, indent=2).encode()+b'\n')
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pck', type=Path, required=True)
    parser.add_argument('--input-eng', type=Path, required=True)
    parser.add_argument('--input-zhs', type=Path, required=True)
    parser.add_argument('--cache-dir', type=Path, required=True)
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    cache = tiles.private_path(args.cache_dir, 'Private profile cache')
    output = tiles.private_path(args.output_dir, 'Private profile output')
    tiles.require(cache != output, 'Cache and output must differ')
    manifest = build_art(tiles.private_path(args.pck, 'Owner PCK'), cache)
    for language, path in (('eng', args.input_eng), ('zhs', args.input_zhs)):
        path = tiles.private_path(path, 'Input pack');target = output/('ui7-'+language+'.nsp')
        tiles.require(path != target, 'Do not overwrite verified input')
        data, receipt = patch_pack(path.read_bytes(), manifest, cache, base_aux=BASE_AUX,
                                  auxiliary=AUXILIARY, input_version=25, version=VERSION,
                                  texts=TEXTS, base_clips=CLIPS, base_strings=STRINGS)
        tiles.atomic_bytes(target, data)
        tiles.atomic_bytes(output/('profile-'+language+'-receipt.json'),
                           json.dumps(receipt, indent=2).encode()+b'\n')
        print(json.dumps(dict(language=language, **receipt)), flush=True)


if __name__ == '__main__':
    main()
