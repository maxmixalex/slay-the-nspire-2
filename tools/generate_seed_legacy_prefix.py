#!/usr/bin/env python3
"""Compact a .NET 9 / ICU invariant-culture StartsWith("old") scalar oracle.

The original NGame selects the invariant culture; RunRngSet uses linguistic
StartsWith, then removes exactly three UTF-16 units. This small fixed-pattern
table represents ignorable characters and combining characters that prevent
the prefix from ending after its d. It is not a general collation engine.
Unicode-derived data is covered by third_party/unicode/LICENSE.
"""
from __future__ import annotations
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(path: Path) -> str:
    source = [tuple(int(v, 16) for v in line.split()) for line in path.read_text().splitlines()]
    for flag, cp in ((2, ord('o')), (4, ord('l')), (8, ord('d'))):
        if [c for c, bits in source if bits & flag] != [cp]:
            raise ValueError('Oracle has additional linguistic letters; review the matching algorithm')
    values = [(cp, bits & 17) for cp, bits in source if bits & 17]
    ranges = []
    for cp, bits in values:
        if bits not in (1, 16):
            raise ValueError('Overlapping prefix categories')
        if ranges and ranges[-1][2] == bits and ranges[-1][1] + 1 == cp:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, bits])
    out = [
        '// Generated by tools/generate_seed_legacy_prefix.py; do not edit.',
        '// Unicode-derived data: third_party/unicode/LICENSE.',
        '// .NET 9 + ICU 74.2, invariant culture, fixed old prefix only.',
        '// A high end bit marks a combining suffix blocker; otherwise ignore.',
        'struct SeedPrefixRange { uint32_t first, end; };',
        'static constexpr SeedPrefixRange SeedPrefixRanges[] = {',
    ]
    for first, last, bits in ranges:
        out.append(f'    {{0x{first:x}, 0x{last | (0x80000000 if bits == 16 else 0):08x}}},')
    out += ['};', 'static_assert(sizeof SeedPrefixRanges == 1896,',
            '              "Legacy prefix data must retain its bounded read-only footprint");', '']
    return '\n'.join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('oracle', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT / 'src/seed_legacy_prefix.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(args.oracle)
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit('Legacy seed table differs from the oracle')
    else:
        args.output.write_text(result)
    print('Legacy prefix: 958 ignorables + 636 blockers; 237 ranges; 1,896 bytes')


if __name__ == '__main__':
    main()
