#!/usr/bin/env python3
"""Emit numeric card-title collation ranks from the owner's pinned private PCK.

NCardGrid compares CardModel.Title using the active .NET CultureInfo. Both
locales and upgraded titles must share a rank space, including equal titles.
Only unsigned rank metadata reaches the C++ output; private strings stay in a
temporary directory and never enter the repository or diagnostic output.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory
from locale_cards import model_rows
from pck import Pack

PROGRAM = r'''
using System.Globalization;
using System.Text.Json;
var input = JsonSerializer.Deserialize<Dictionary<string, string[]>>(File.ReadAllText(args[0]))!;
var output = new Dictionary<string, int[]>();
foreach (var pair in input) {
    var compare = CultureInfo.GetCultureInfo(pair.Key).CompareInfo;
    var order = Enumerable.Range(0, pair.Value.Length).ToArray();
    Array.Sort(order, (a,b) => compare.Compare(pair.Value[a],pair.Value[b],CompareOptions.None));
    var ranks = new int[order.Length];var rank=0;
    for (var i=0;i<order.Length;i++) {
        if(i>0 && compare.Compare(pair.Value[order[i-1]],pair.Value[order[i]],CompareOptions.None)!=0)rank++;
        ranks[order[i]]=rank;
    }
    output[pair.Key]=ranks;
}
File.WriteAllText(args[1],JsonSerializer.Serialize(output));
'''
PROJECT = '''<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>Exe</OutputType><TargetFramework>net8.0</TargetFramework><ImplicitUsings>enable</ImplicitUsings><Nullable>enable</Nullable><RestoreIgnoreFailedSources>true</RestoreIgnoreFailedSources><NuGetAudit>false</NuGetAudit></PropertyGroup></Project>'''


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pck',required=True,type=Path)
    parser.add_argument('--dotnet',default='dotnet')
    parser.add_argument('--work',required=True,type=Path,help='Private temporary build directory')
    parser.add_argument('--output',type=Path,default=Path('src/card_title_sort_rank.inc'))
    args=parser.parse_args();args.work.mkdir(parents=True,exist_ok=True)
    models=model_rows();pack=Pack(args.pck);text={}
    for language,culture in [('eng','en-US'),('zhs','zh-CN')]:
        table=json.loads(pack.read(f'localization/{language}/cards.json'))
        names=[table[row['key']+'.title'] for row in models]
        text[culture]=names+[name+'+' for name in names]
    pack.close()
    with TemporaryDirectory(prefix='card-title-sort-',dir=args.work) as scratch:
        work=Path(scratch)
        (work/'sort.csproj').write_text(PROJECT)
        (work/'Program.cs').write_text(PROGRAM)
        (work/'input.json').write_text(json.dumps(text,ensure_ascii=False))
        subprocess.run([args.dotnet,'run','--project',str(work/'sort.csproj'),'--configuration','Release','--',str(work/'input.json'),str(work/'ranks.json')],check=True)
        ranks=json.loads((work/'ranks.json').read_text())
    lines=['// Numeric collation metadata only. Generated by generate_card_title_sort.py.',
           '// v0.111.0 / 41cef1ea; .NET CultureInfo en-US / zh-CN, CompareOptions.None.',
           '// Each locale contains base then upgraded CardModel.Title ranks; ties stay equal.',
           'static constexpr uint16_t card_title_sort_rank[2][CardKinds*2]={']
    for culture in ('en-US','zh-CN'):
        row=ranks[culture]
        if len(row)!=len(models)*2 or any(type(n)!=int or not 0<=n<len(row) for n in row):
            raise ValueError('Invalid numeric title ranks')
        lines.append(' {')
        for i in range(0,len(row),24):lines.append('  '+','.join(map(str,row[i:i+24]))+',')
        lines.append(' },')
    lines.append('};')
    args.output.write_text('\n'.join(lines)+'\n')
    print(f'Wrote two locale rank tables, {len(models)} models and both upgrade states; no private strings.')


if __name__=='__main__':main()
