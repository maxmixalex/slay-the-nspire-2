"""Generate compact runtime IDs/tables from reviewed public source metadata.

No original localization text, assembly or artwork is embedded here.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]

def generated_files():
    source=json.loads((ROOT/'config/timeline-0.111.0.json').read_text())
    text=json.loads((ROOT/'config/timeline-text-ui24.json').read_text())
    rows=source['epochs']
    assert len(rows)==57 and text['epoch_order']==[r['id'] for r in rows]
    names={r['model']:r['model'].removesuffix('Epoch') for r in rows}
    parents={child:r['model'] for r in rows for child in r['expands']}
    assert len(parents)==56 and 'NeowEpoch' not in parents
    output=['// Generated by tools/timeline_profile.py; numeric routing metadata only.\n',
            'constexpr TimelineEpoch timeline_epochs[EpochCount]={\n']
    for row in rows:
        kind=next((k for k in ('cards','relics','potions','events') if k in row),None)
        models=[]
        for model in row.get(kind,[]) if kind else []:
            if kind=='cards':
                prefix=next((c for c in ('Defect','Regent','Necrobinder') if row['model'].startswith(c)), '')
                model={'Necrobinder':'Necro'}.get(prefix,prefix)+model
            elif kind=='relics':model='WorldRelic'+model
            elif kind=='potions':model='unsigned(Potion::'+{'BloodPotion':'Blood'}.get(model,model)+')'
            else:model='unsigned(OriginalEventId::'+model+')'
            models.append(model)
        story=text['story_order'].index(row['story'].upper()) if row.get('story') else 255
        parent='Epoch::'+names[parents[row['model']]] if row['model'] in parents else 'Epoch::Count'
        cls={'cards':'Card','relics':'Relic','potions':'Potion','events':'Event'}.get(kind,'None')
        output.append(f' {{{row["era"]},{{{",".join(models+["0"]*(3-len(models)))}}},{parent},{row["position"]},{story},unsigned(TimelineKind::{cls}),{len(models)}}},\n')
    output.append('};\nconst TimelineAgnostic timeline_agnostic[TimelineAgnosticCount]={\n')
    output.extend(f' {{Epoch::{names[r["model"]]},{r["score"]}}},\n' for r in source['agnostic'])
    output.append('};\n')
    output.append('template<unsigned N>struct TimelineModelMap {uint8_t values[N]{};\n'
                  ' constexpr TimelineModelMap(TimelineKind kind){\n'
                  '  for(auto&value:values)value=EpochCount;\n'
                  '  for(unsigned i=0;i<EpochCount;++i)if(timeline_epochs[i].kind==unsigned(kind))\n'
                  '   for(unsigned j=0;j<timeline_epochs[i].count;++j)if(timeline_epochs[i].models[j]<N)values[timeline_epochs[i].models[j]]=i;\n'
                  ' }};\n')
    for kind,limit in [('card','CardKinds'),('relic','WorldRelicKinds'),('potion','PotionKinds+1'),('event','OriginalEventKinds+1')]:
        output.append(f'static constexpr TimelineModelMap<{limit}> timeline_{kind}_epochs(TimelineKind::{kind.title()});\n')
    base=text['string_base'];count=base+len(text['strings'])
    header=['#pragma once\n// Generated text positions only; original bytes stay private.\nnamespace spire {\n',
            f'constexpr unsigned TimelineTextBase={base},TimelineStringCount={count};\n',
            f'constexpr unsigned TimelineStoryBase={base+57*4};\n']
    for i,item in enumerate(text['strings']):
        if item['table']=='timeline':
            name='T24_'+''.join(c if c.isalnum() else '_' for c in item['key'])
            header.append(f'constexpr unsigned {name}={base+i};\n')
    header.append('}\n')
    return {'include/timeline_ids.inc':''.join(' '+names[r['model']]+',\n' for r in rows),
            'include/timeline_text.hpp':''.join(header),'src/timeline_data.inc':''.join(output)}

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,data in generated_files().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=data:raise SystemExit('Generated timeline table differs: '+name)
        else:path.write_text(data)
