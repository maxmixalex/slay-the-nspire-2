#!/usr/bin/env python3
"""Generate the exact, allocation-free two-fragment native text key table."""

from __future__ import annotations

import argparse
import hashlib
import json
import re

from nspire_converter.paths import ROOT
from nspire_converter.source_tables import cpp_tokens

SOURCE = ROOT / "cpp/src/detail/data/world_text_index.hpp"
OUTPUT = ROOT / "cpp/src/detail/data/world_text_fragments.hpp"
ROW = re.compile(r'\{\s*("(?:[^"\\]|\\.)*")\s*,\s*(\d+)\s*\},?')


def read_rows(text):
    rows = []
    for number, line in enumerate(text.splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        match = ROW.fullmatch(line)
        if not match:
            raise ValueError(f"Unsupported source row at line {number}")
        key = json.loads(match[1])
        value = int(match[2])
        if (
            any(ord(c) < 32 or ord(c) >= 127 for c in key)
            or "." not in key
            or not 0 <= value <= 65535
        ):
            raise ValueError(f"Invalid grouped key or value at line {number}")
        if rows and key <= rows[-1][0]:
            raise ValueError("Source keys must be unique and sorted")
        rows.append((key, value))
    if not rows or len(rows) > 65535:
        raise ValueError("Invalid source row count")
    return rows


class Pool:
    def __init__(self):
        self.offsets = {}
        self.bytes = 0

    def intern(self, text):
        if text not in self.offsets:
            self.offsets[text] = self.bytes
            self.bytes += len(text) + 1
            if self.bytes > 65536:
                raise ValueError("Fragment pool exceeds exact16-bit offsets")
        return self.offsets[text]


def pack(rows):
    prefixes, suffixes, groups = Pool(), Pool(), Pool()
    prefix_offsets = []
    suffix_offsets = []
    values = []
    group_offsets = []
    first = []
    end = []
    previous = None
    for i, (key, value) in enumerate(rows):
        group, local = key.split(".", 1)
        if group != previous:
            if previous is not None:
                end.append(i)
            group_offsets.append(groups.intern(group))
            first.append(i)
            previous = group
        prefix, dot, suffix = local.partition(".")
        if dot:
            prefix += "."
        else:
            prefix, suffix = "", local
        prefix_offsets.append(prefixes.intern(prefix))
        suffix_offsets.append(suffixes.intern(suffix))
        values.append(value)
    end.append(len(rows))
    return dict(
        prefixes=prefixes,
        suffixes=suffixes,
        groups=groups,
        prefix_offsets=prefix_offsets,
        suffix_offsets=suffix_offsets,
        values=values,
        group_offsets=group_offsets,
        first=first,
        end=end,
    )


def render(source):
    rows = read_rows(source)
    table = pack(rows)
    lines = [
        "// Generated by python/src/nspire_converter/build_world_text_fragments.py; do not edit.",
        "// Public names and numeric IDs only. Source SHA-256: "
        + hashlib.sha256(source.encode()).hexdigest(),
        "static constexpr packed_content_index::Fragments<"
        + ",".join(
            map(
                str,
                (
                    len(rows),
                    table["prefixes"].bytes,
                    table["suffixes"].bytes,
                    table["groups"].bytes,
                    len(table["first"]),
                ),
            )
        )
        + "> world_text_index{",
    ]
    for name in ("prefix_offsets", "suffix_offsets", "values", "group_offsets", "first", "end"):
        values = table[name]
        lines.append(" { // " + name)
        for at in range(0, len(values), 20):
            lines.append("  " + ",".join(map(str, values[at : at + 20])) + ",")
        lines.append(" },")
    for name in ("prefixes", "suffixes", "groups"):
        strings = list(table[name].offsets)
        lines.append(" // " + name)
        for i, text in enumerate(strings):
            lines.append(
                " "
                + json.dumps(text, ensure_ascii=True)
                + (' "\\0"' if i + 1 < len(strings) else ",")
            )
    lines.extend(["};", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(SOURCE.read_text())
    if args.check:
        if cpp_tokens(OUTPUT.read_text()) != cpp_tokens(generated):
            raise SystemExit("Regenerate the text key fragments from the authoritative source")
    else:
        OUTPUT.write_text(generated)
    table = pack(read_rows(SOURCE.read_text()))
    print(
        json.dumps(
            {
                "entries": len(table["values"]),
                "prefix_bytes": table["prefixes"].bytes,
                "suffix_bytes": table["suffixes"].bytes,
                "groups": len(table["first"]),
                "generated_sha256": hashlib.sha256(generated.encode()).hexdigest(),
            }
        )
    )


if __name__ == "__main__":
    main()
