"""Complete fresh original-game artwork and publish matching calculator data.

Inputs are the editions generated by this recipe. Historical private packs,
recovery spools and manually prepared receipts are never required. Final index
pruning requires the matching linked ARM decoder and checks every candidate.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

from nspire_converter.paths import ROOT

# Accepted UI23 artwork policy. Reduced editions keep their original colors.
DEFAULT_QUALITY_POLICY = "bounded-a5"
DEFAULT_PRESERVE_SELECTION = False
DEFAULT_SELECTION_POLICY = "dark-safe-a6"
DEFAULT_SELECTION_OVERRIDES = {0: "555a8", 2: "555a8", 3: "555a8"}


def fresh_sparse_images(source):
    from nspire_converter.actor_storage_policy import exact_material_images

    protected = exact_material_images(source)
    return {
        image
        for image, descriptor in enumerate(source.images)
        if image not in protected and descriptor[3] != 6 and source.image_raw(image)[2] == 4
    }


def save_result(path, data, receipt):
    from nspire_converter import content_tiles as t

    path = Path(path)
    receipt.update(complete=True, output_bytes=len(data), output_sha256=t.sha256(data))
    t.atomic_bytes(path, data)
    t.atomic_bytes(path.with_suffix(".json"), (json.dumps(receipt, indent=2) + "\n").encode())
    print(
        json.dumps(
            {
                key: value
                for key, value in receipt.items()
                if key in ("complete", "output_bytes", "output_sha256", "stage")
            }
        ),
        flush=True,
    )


def retile_fresh(input_path, output_path, work, workers):
    """Dice newly sampled sparse actor pieces without a restoration archive."""
    from nspire_converter import coalesce_tile_resources as coalesce
    from nspire_converter import content_tiles as t
    from nspire_converter import retile_appended_resources as retile
    from nspire_converter import retile_character as dice

    data = Path(input_path).read_bytes()
    source = coalesce.view(data)
    t.require(
        source.version == 44 and len(source.aux) == 7206,
        "Fresh actor dicing requires the complete original-derived UI22 actor catalog",
    )
    work = Path(work)
    work.mkdir(parents=True, exist_ok=True)
    # Registered overflow pieces are auxiliary roots, not ordinary clip
    # samples. Inspect every retained sparse image so those pieces are included.
    from nspire_converter.actor_storage_policy import exact_material_images, verify_exact_materials

    protected = exact_material_images(source)
    selected = fresh_sparse_images(source)
    if selected:
        plan = dice.make_plan(source, work, selected, precision=8)
        plan["compact_replaced_directory"] = True
        encoded = retile.compress_plan(plan, work, work / "encoded", workers)
        output, details = retile.rewrite(source, plan, encoded)
        proof = dice.verify(source, output, plan, work)
    else:
        output, details, proof = data, {}, {"exact_sparse_images": 0}
    material_proof = verify_exact_materials(source, coalesce.view(output), protected)
    save_result(
        output_path,
        output,
        dict(
            stage="fresh_actor_dicing",
            input_sha256=t.sha256(data),
            selected_sparse_images=len(selected),
            precision="RGB565/alpha8 exact",
            historical_recovery_inputs=False,
            details=details,
            verification=proof,
            exact_actor_materials=material_proof,
        ),
    )


def codec45(input_path, output_path, work, workers):
    import struct

    from nspire_converter import coalesce_tile_resources as coalesce
    from nspire_converter import content_tiles as t

    data = Path(input_path).read_bytes()
    source = coalesce.view(data)
    t.require(
        source.version == 44, "Selection preparation requires the preceding fresh NSP2/44 pack"
    )
    # NSP45 remains compatible with the existing dense TGR1/TGR2 streams.
    # Keep them intact: optional color conversion must not receive TGR3 data,
    # and changing a codec is unnecessary for the selection representation.
    mutable = bytearray(data)
    struct.pack_into("<I", mutable, 4, 45)
    output = bytes(mutable)
    target = coalesce.view(output)
    t.require(
        output[:4] == data[:4]
        and output[8:] == data[8:]
        and target.images == source.images
        and target.clips == source.clips
        and target.aux == source.aux,
        "Wire version preparation changed resource payloads",
    )
    save_result(
        output_path,
        output,
        dict(
            stage="selection_codec45",
            input_sha256=t.sha256(data),
            existing_pixel_codecs_unchanged=True,
            all_payload_bytes_unchanged=True,
        ),
    )


def optional_prune(input_path, output_path, elf_path):
    from nspire_converter import content_tiles as t

    data = Path(input_path).read_bytes()
    elf = Path(elf_path) if elf_path else None
    if elf is not None and elf.is_file():
        from nspire_converter.prune_orphan_index_records import ArmIndices, convert_bytes

        output, details = convert_bytes(data, ArmIndices(elf))
        details["optimization_executed"] = True
    else:
        output = data
        details = dict(
            optimization_executed=False,
            reason="Optional complete linked-ARM profiling requires a matching launcher ELF; all records retained",
            orphan_records_removed=0,
            saved_bytes=0,
        )
    save_result(
        output_path,
        output,
        dict(details, stage="optional_orphan_pruning", input_sha256=t.sha256(data)),
    )


def mandatory_prune(input_path, output_path, helper_folder):
    from nspire_converter import content_tiles as t
    from nspire_converter.converter_arm_validation import verify
    from nspire_converter.prune_orphan_index_records import ArmIndices, convert_bytes

    elf, manifest = verify(helper_folder)
    data = Path(input_path).read_bytes()
    output, proof = convert_bytes(
        data,
        ArmIndices(elf),
        progress=lambda row: print(
            json.dumps(dict(stage="final_orphan_index_group", **row)), flush=True
        ),
    )
    save_result(
        output_path,
        output,
        dict(
            proof,
            stage="mandatory_final_orphan_pruning",
            input_sha256=t.sha256(data),
            validation_helper_sha256=manifest["elf_sha256"],
            real_linked_arm_required=True,
        ),
    )


def quality(
    input_path,
    output_path,
    work,
    workers,
    policy,
    preserve_selection,
    selection_policy=None,
    selection_overrides=None,
):
    from nspire_converter import content_tiles as t

    data = Path(input_path).read_bytes()
    if policy == "exact":
        save_result(
            output_path,
            data,
            dict(stage="quality", policy="exact", input_sha256=t.sha256(data), exact_pixels=True),
        )
        return
    from nspire_converter import animation_color_candidates as colors
    from nspire_converter import coalesce_color_candidates as coalescer
    from nspire_converter.actor_storage_policy import exact_material_images, verify_exact_materials
    from nspire_converter.quantize_animation_resources import rewrite
    from nspire_converter.retile_appended_resources import view

    source = view(data)
    results = colors.convert(
        source,
        policy,
        workers=workers,
        preserve_static=True,
        preserve_selection=preserve_selection,
        selection_policy=selection_policy,
        selection_overrides=selection_overrides,
    )
    quantized = rewrite(source, {}, results)
    proof = colors.verify(source, quantized, results, policy, selection_policy, selection_overrides)
    output, compaction = coalescer.convert(quantized, Path(work), workers=workers)
    material_proof = verify_exact_materials(source, view(output), exact_material_images(source))
    save_result(
        output_path,
        output,
        dict(
            stage="quality",
            policy=policy,
            input_sha256=t.sha256(data),
            static_art_preserved=True,
            selection_art_preserved=preserve_selection,
            selection_policy=selection_policy,
            selection_overrides=selection_overrides or {},
            color_verification=proof,
            exact_actor_materials=material_proof,
            exact_tile_coalescing=compaction,
        ),
    )


def sparse_exact(input_path, output_path, work, workers):
    from nspire_converter import coalesce_tile_resources as coalesce
    from nspire_converter import compact_sparse_tiles as sparse
    from nspire_converter import content_tiles as t

    data = Path(input_path).read_bytes()
    source = coalesce.view(data)
    plan, details = sparse.make_plan(source, Path(work), workers=workers)
    # Implicit frame geometry requires version 46 even though TGR3 began at 45.
    output, _ = coalesce.rewrite(data, plan, version=source.version)
    proof = sparse.verify(data, output, plan)
    t.require(len(output) <= len(data), "Exact sparse conversion increased the resource")
    save_result(
        output_path,
        output,
        dict(
            stage="exact_sparse_tiles",
            input_sha256=t.sha256(data),
            exact_pixels=True,
            resident_bytes_added=0,
            details=details,
            verification=proof,
        ),
    )


def retune_exact(input_path, output_path, work, workers):
    from nspire_converter import content_tiles as t
    from nspire_converter import retune_color_contexts as retune

    data = Path(input_path).read_bytes()
    output, proof = retune.convert(data, Path(work), workers=workers)
    t.require(len(output) <= len(data), "Exact literal-context retuning increased the resource")
    save_result(
        output_path,
        output,
        dict(
            stage="exact_literal_contexts",
            input_sha256=t.sha256(data),
            exact_pixels=True,
            resident_bytes_added=0,
            literal_contexts_never_larger=True,
            profiles=retune.PROFILES,
            verification=proof,
        ),
    )


def validate_install(artwork_path, output, codes, no_animations, original_reference=None):
    from nspire_converter import coalesce_tile_resources as coalesce
    from nspire_converter import content_tiles as t
    from nspire_converter import no_animations as reduced
    from nspire_converter import split_content as split
    from nspire_converter import storage_parts as storage
    from nspire_converter.converter_storage import edition_files
    from nspire_converter.release_content_guard import validate_release_content

    output = Path(output)
    directory = output / "data"
    started = time.monotonic()
    artwork = Path(artwork_path).read_bytes()
    source = coalesce.view(artwork)
    t.require(
        reduced.reduced(artwork) == no_animations,
        "Requested animation profile does not match the artwork",
    )
    guard = validate_release_content(artwork, "ui26")
    from nspire_converter.card_affliction import validate as validate_cards

    continuous_cards = validate_cards(source, source.image_raw)
    t.require(
        continuous_cards is not None, "The final converter requires continuous card materials"
    )
    refresh = json.loads((directory / "artwork-refresh-receipt.json").read_text())
    common = storage.join_parts(
        (directory / "nSpire2.dat.tns").read_bytes(),
        {name: (directory / name).read_bytes() for name in storage.PART_FILES},
    )
    locales = {}
    for code in codes:
        logical = split.reconstruct(
            common, (directory / f"nSpire2.{code}.dat.tns").read_bytes(), code
        )
        view = coalesce.view(logical)
        t.require(
            t.sha256(logical) == refresh["locales"][code]["logical_sha256"],
            "Published locale differs from its verified artwork refresh",
        )
        t.require(
            len(view.images) == len(source.images)
            and all(before[1:] == after[1:] for before, after in zip(source.images, view.images)),
            "Published locale image catalog differs",
        )
        t.require(
            view.cards == source.cards and view.clips == source.clips and view.aux == source.aux,
            "Published locale has mismatched gameplay or animation identities",
        )
        if refresh.get("character_unlock_original_text"):
            from nspire_converter.character_unlock_text import STRINGS

            labels = refresh["locales"][code]["character_unlock"]
            t.require(
                len(view.strings) == STRINGS
                and labels["complete"]
                and labels["verification"]["missing_required_glyphs"] == 0
                and labels["original_utf8_recovered_from_graphemes"],
                "Published character lock text or font coverage is incomplete",
            )
        t.require(
            reduced.reduced(logical) == no_animations,
            "Published locale lost its presentation profile",
        )
        locales[code] = dict(
            logical_bytes=len(logical),
            logical_sha256=t.sha256(logical),
            stored_bytes=(directory / f"nSpire2.{code}.dat.tns").stat().st_size,
            glyphs=len(view.glyphs),
            strings=len(view.strings),
            roundtrip_verified=True,
        )
    from nspire_converter.source_version import normalize_version, write_version

    if not isinstance(original_reference, dict):
        raise ValueError("Original game version is missing from the conversion context")
    version_path = write_version(directory, normalize_version(original_reference.get("version")))
    files = edition_files(directory, codes)
    files.append(version_path)
    unexpected = [
        code
        for code in split.LANGUAGES
        if code not in codes and (directory / f"nSpire2.{code}.dat.tns").exists()
    ]
    t.require(
        not unexpected,
        "Output contains unrequested old locale files; choose a clean output directory: "
        + ",".join(unexpected),
    )
    report = dict(
        schema=1,
        status="complete",
        complete=True,
        source="original-game-directory",
        original_game=original_reference,
        content_version=source.version,
        common_sha256=t.sha256(common),
        artwork_sha256=t.sha256(artwork),
        languages_require_this_exact_common=True,
        animation_profile="reduced-poses" if no_animations else "full",
        original_clip_counts_clocks_pivots_unchanged=True,
        languages=codes,
        installed_data_bytes=sum(path.stat().st_size for path in files),
        files={
            path.name: dict(bytes=path.stat().st_size, sha256=t.sha256(path.read_bytes()))
            for path in files
        },
        locales=locales,
        release_content=guard,
        continuous_card_materials=continuous_cards,
        elapsed_seconds=time.monotonic() - started,
        launcher_included=False,
        calculator_performance_measured=False,
        shader_precision=dict(
            source_clock_zero=no_animations,
            source_clock_zero_scope="Ancient NPC/background presentation only; card/UI clocks continue",
            reviewed_half_noise=len(source.aux) >= 7228,
            half_noise_scope="Tez basic/triangle noise; shared triangle also used by Neow fires",
            original_full_resolution_shader_pixels_exact=False,
        )
        if len(source.aux) >= 7228
        else None,
    )
    t.atomic_bytes(
        output / "converter-receipt.json", (json.dumps(report, indent=2) + "\n").encode()
    )
    print(
        json.dumps(
            {
                key: report[key]
                for key in (
                    "status",
                    "content_version",
                    "animation_profile",
                    "languages",
                    "installed_data_bytes",
                )
            }
        ),
        flush=True,
    )


def execute_builtin(module, arguments):
    if module == "@fresh-actor-dicing":
        retile_fresh(arguments[0], arguments[1], arguments[2], int(arguments[3]))
    elif module == "@fresh-codec45":
        codec45(arguments[0], arguments[1], arguments[2], int(arguments[3]))
    elif module == "@optional-orphan-prune":
        optional_prune(*arguments)
    elif module == "@mandatory-orphan-prune":
        mandatory_prune(*arguments)
    elif module == "@final-quality":
        quality(
            arguments[0],
            arguments[1],
            arguments[2],
            int(arguments[3]),
            arguments[4],
            arguments[5] == "true",
            arguments[6] or None,
            {int(key): value for key, value in json.loads(arguments[7]).items()},
        )
    elif module == "@final-sparse":
        sparse_exact(arguments[0], arguments[1], arguments[2], int(arguments[3]))
    elif module == "@final-retune":
        retune_exact(arguments[0], arguments[1], arguments[2], int(arguments[3]))
    elif module == "@validate-install":
        validate_install(
            arguments[0],
            arguments[1],
            arguments[2].split(","),
            arguments[3] == "true",
            json.loads(arguments[4]),
        )
    else:
        return False
    return True


