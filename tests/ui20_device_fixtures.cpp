// Production-codec inputs for ordinary device Continue, Give Up and map/event
// presentation. Only the untouched opening-room pair has complete run facts;
// Ancient/act warps are explicitly partial controlled fixtures, not victories.
#include "app.hpp"
#include "debug_commands.hpp"
#include "original_events.hpp"
#include "world_run.hpp"
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <filesystem>
#include <string>

using namespace spire;
static App app;
static State decoded;
static SaveData encoded,roundtrip;
static UiProgress decoded_progress;
static uint8_t progress_bytes[UiProgressCapacity],progress_roundtrip[UiProgressCapacity];
static std::string output;
static unsigned checks;
#define CHECK(x) do{++checks;if(!(x)){std::fprintf(stderr,"UI20 fixture:%d %s\n",__LINE__,#x);std::exit(1);}}while(0)
static void write(const std::string&name,const void*data,size_t bytes){
 FILE*f=std::fopen((output+"/"+name).c_str(),"wb");CHECK(f);
 CHECK(std::fwrite(data,1,bytes,f)==bytes);CHECK(!std::fclose(f));
}
static void fresh(){
 app.callbacks={};app.forget_run_checkpoint();app.reset_presentation();
 app.title=app.paused=app.character_select=app.library=false;
 new_run(app.game,0x20c467,false,Character::Ironclad);
 CHECK(world_set_seed(app.game,"UI20-ORIGINAL-VIEWPORT"));
 CHECK(world_begin_run(app.game,reference::ActKind::Overgrowth,3));
 CHECK(app.game.original_events.id==OriginalEventId::Neow&&app.game.world.total_floor==1);
 clear_ui_progress(app.progress);app.progress_loaded=true;app.progress_dirty=true;
}
static void emit(const std::string&stem,bool complete){
 CHECK(validate(app.game));app.begin_progress(!complete);app.sync_progress();
 CHECK(ui_run_facts_complete(app.progress.current)==complete);
 CHECK(app.progress.current.partial==!complete&&!app.progress.current.outcome);
 CHECK(save(app.game,encoded)&&load(decoded,encoded.bytes,encoded.size)&&save(decoded,roundtrip));
 CHECK(roundtrip.size==encoded.size&&!std::memcmp(encoded.bytes,roundtrip.bytes,encoded.size));
 const size_t bytes=encode_ui_progress(app.progress,progress_bytes,sizeof progress_bytes);CHECK(bytes);
 CHECK(decode_ui_progress(progress_bytes,bytes,decoded_progress));
 const size_t again=encode_ui_progress(decoded_progress,progress_roundtrip,sizeof progress_roundtrip);
 CHECK(again==bytes&&!std::memcmp(progress_bytes,progress_roundtrip,bytes));
 CHECK(decoded_progress.current.seed==decoded.seed&&decoded_progress.current.run_seed==decoded.world.run_seed);
 CHECK(ui_run_facts_complete(decoded_progress.current)==complete);
 write(stem+".sav.tns",encoded.bytes,encoded.size);
 write(stem+".progress.tns",progress_bytes,bytes);
 std::printf("%s: NSR=%u NSH=%zu phase=%u act=%u event=%s complete=%u partial=%u\n",
  stem.c_str(),unsigned(encoded.size),bytes,unsigned(decoded.phase),unsigned(decoded.world.act_index)+1,
  original_event_key(decoded.original_events.id),unsigned(complete),unsigned(decoded_progress.current.partial));
}
int main(int argc,char**argv){
 CHECK(argc==2);output=argv[1];std::filesystem::create_directories(output);
 const struct {OriginalEventId id;const char*key;} ancients[]={
  {OriginalEventId::Neow,"neow"},{OriginalEventId::Darv,"darv"},
  {OriginalEventId::Nonupeipe,"nonupeipe"},{OriginalEventId::Orobas,"orobas"},
  {OriginalEventId::Pael,"pael"},{OriginalEventId::Tanx,"tanx"},
  {OriginalEventId::Tezcatara,"tezcatara"},{OriginalEventId::Vakuu,"vakuu"}};
 for(const auto&entry:ancients){fresh();
  if(entry.id!=OriginalEventId::Neow)CHECK(debug_enter_room(app.game,WorldRoom::Event,EncounterId::None,entry.id));
  emit(std::string("ui20-ancient-")+entry.key,entry.id==OriginalEventId::Neow);
 }
 for(unsigned act=1;act<=2;++act){fresh();CHECK(debug_enter_act(app.game,act));
  CHECK(app.game.phase==Phase::Map&&app.game.world.act_index==act);
  emit("ui20-map-act"+std::to_string(act+1),false);
 }
 const char note[]=
  "Controlled UI20 device fixtures, never release saves. Generated by the production NSR/NSH codecs; all pairs decode and re-encode identically.\n"
  "Install a pair as state/nSpire2.sav.tns and state/nSpire2.progress.tns in an isolated test profile; read back both before launching.\n"
  "ui20-ancient-neow is the untouched first room of a new seeded Ironclad A3 run. Its progress starts from the real beginning, has complete facts and no missing prefix. Continue, wait for the room, press Escape, choose Give Up, confirm Yes. The ordinary abandon must delete sav/bak/tmp and show the defeat screen. Wait for Continue, activate it and wait for the summary: floors, observed gold and ascension produce three score lines. This checks the complete score layout without fabricating a battle or editing a terminal save. Activate Main Menu to inspect the 800 ms fade-out, black boundary and 800 ms fade-in.\n"
  "The other seven Ancient pairs use the actual debug_enter_room constructor and are marked partial because their rooms were supplied. Continue and wait one second for their original option entry; inspect the full background behind the top bar.\n"
  "ui20-map-act2 and ui20-map-act3 use the actual act constructor, retain valid earlier graphs and explicitly mark the skipped prefix partial. Continue to the standalone map, wait for its opening tween and pan vertically: uncovered areas must remain black.\n"
  "The source scenario begins with 0x20c467 and UI20-ORIGINAL-VIEWPORT, Overgrowth, ascension 3. No RAM patch, fake score, prerecorded death pose or image is placed in any save.\n";
 write("README-ui20.txt",note,sizeof note-1);
 std::printf("UI20 production-codec fixtures: %u checks passed\n",checks);
}
